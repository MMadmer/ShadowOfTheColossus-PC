TRANSLATIONS = {lang: {pt: texts[i] for pt, texts in TEXTS.items()} for i, lang in enumerate(LANGUAGES)}


def translate(pt, en, lang):
    """pt or en as given for Portuguese and English, else the text in lang (English when missing)."""
    if lang == 'pt':
        return pt
    table = TRANSLATIONS.get(lang)
    return table.get(pt, en) if table else en
