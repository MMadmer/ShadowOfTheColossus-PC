Lang Current() {
    static const Lang lang = [] {
        const char* v = std::getenv("SOTC_UI_LANG");
        if (!v || !v[0] || !v[1]) {
            return Lang::En;
        }
        // The language part of the code ("pt", "zh_CN", "ja-JP").
        const char code[] = {char(std::tolower(static_cast<unsigned char>(v[0]))),
                             char(std::tolower(static_cast<unsigned char>(v[1]))), '\0'};
        static constexpr std::pair<std::string_view, Lang> codes[] = {
            {"pt", Lang::Pt}, {"en", Lang::En}, {"es", Lang::Es}, {"ru", Lang::Ru},
            {"zh", Lang::Zh}, {"ja", Lang::Ja}, {"ko", Lang::Ko},
        };
        for (const auto& [name, value] : codes) {
            if (name == code) {
                return value;
            }
        }
        return Lang::En;
    }();
    return lang;
}

const char* T(const char* pt, const char* en) {
    const Lang lang = Current();
    if (lang == Lang::Pt) {
        return pt;
    }
    if (lang == Lang::En) {
        return en;
    }
    static const auto table = [] {
        std::unordered_map<std::string_view, const Texts*> map;
        map.reserve(std::size(kTexts));
        for (const Texts& texts : kTexts) {
            map.emplace(texts.pt, &texts);
        }
        return map;
    }();
    const auto it = table.find(pt);
    if (it == table.end()) {
        return en;
    }
    const char* text = it->second->tr[static_cast<int>(lang) - static_cast<int>(Lang::Es)];
    return text && text[0] ? text : en;
}

